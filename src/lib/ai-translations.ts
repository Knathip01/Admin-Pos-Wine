export const AI_TRANSLATIONS: Record<Language, Record<string, string>> = Object.fromEntries(
  LANGUAGES.map((lang) => [lang, { ...AI_EN, ...AI_OVERRIDES[lang] }])
) as Record<Language, Record<string, string>>;

export function getAiString(language: Language, key: string): string {
  const pack = AI_TRANSLATIONS[language] || AI_TRANSLATIONS.en;
  return pack[key] || AI_TRANSLATIONS.en[key] || key;
}

export function formatAiTemplate(
  template: string,
  vars: Record<string, string | number>
): string {
  return Object.entries(vars).reduce(
    (text, [k, v]) => text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v)),
    template
  );
}

export function formatAiPrice(price: number, language: Language): string {
  const locale = AI_PRICE_LOCALES[language] || 'en-US';
  try {
    return new Intl.NumberFormat(locale, {
      style: 'currency',
      currency: 'THB',
      maximumFractionDigits: 0,
    }).format(price);
  } catch {
    return `฿${price.toLocaleString()}`;
  }
}

